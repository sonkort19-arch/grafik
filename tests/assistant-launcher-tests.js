const fs=require('fs');
const assert=require('assert');
const src=fs.readFileSync('assistant-attendance.js','utf8');
const icon=fs.readFileSync('assets/ma-assistant-icon.svg','utf8');
assert(src.includes("/assets/ma-assistant-icon.svg"),'launcher must use the branded MA icon asset');
assert(icon.includes('stroke="#a8ff00"')&&icon.includes('stroke="#b7ff1a"'),'icon must preserve black and neon-green MA identity');
assert(src.includes('aria-label\",\"Открыть помощника МА График'),'launcher must keep accessible label');
assert(src.includes('bottom:calc(96px + env(safe-area-inset-bottom))'),'mobile launcher must stay clearly above bottom navigation');
assert(src.includes('right:20px')&&src.includes('width:48px')&&src.includes('height:48px'),'mobile launcher must be compact, inset and retain a 44px+ touch target');
assert(src.includes('0 5px 15px rgba(0,0,0,.20)'),'launcher shadow must remain restrained');
assert(src.includes('.ma-assistant-launch:active{transform:scale(.96)}'),'launcher needs tactile press feedback');
console.log('assistant launcher tests: OK');
